using static TypeSharp.Test.ModelTests;

namespace TypeSharp.Test;

public class ModelTests
{
    public enum HttpStatus
    {
        None,
        OK = 200,
        NotFound = 404,
    }

    public class NormalModel
    {
        public Guid Guid { get; set; }
        public int Int { get; set; }
        public string Str { get; set; }
        public object Obj { get; set; }
        public HttpStatus Status { get; set; }
        public DateOnly DateOnly { get; set; }

        public required Guid RequiedGuid { get; set; }
        public required int RequiedInt { get; set; }
        public required string RequiedStr { get; set; }
        public required object RequiedObj { get; set; }
        public required HttpStatus RequiedStatus { get; set; }
        public required DateOnly RequiedDateOnly { get; set; }

        public int OnlyGet { get; }
        public int PrivateSet { get; private set; }
    }

    public class NullableModel
    {
        public Guid? Guid { get; set; }
        public int? Int { get; set; }
        public string? Str { get; set; }
        public object? Obj { get; set; }
        public HttpStatus? Status { get; set; }
        public DateOnly? DateOnly { get; set; }

        public required Guid? RequiedGuid { get; set; }
        public required int? RequiedInt { get; set; }
        public required string RequiedStr { get; set; }
        public required object? RequiedObj { get; set; }
        public required HttpStatus? RequiedStatus { get; set; }
        public required DateOnly? RequiedDateOnly { get; set; }

        public int? OnlyGet { get; }
        public int? PrivateSet { get; private set; }
    }


    public class Generic<T>
    {
        public required T Value { get; set; }
    }

    public class GenericModel
    {
        public required Generic<string> GenericString { get; set; }
        public required Generic<Guid> GenericGuid { get; set; }
    }

    public class TypeEnum
    {
        public const string Class = "class";
        public const string Struct = "struct";
    }

    [Fact]
    public void Test()
    {
        var _generator = new TypeScriptGenerator(new()
        {
            CamelCase = true,
            //DetectionMode = DetectionMode.AutoDetect,
        })
        {
            typeof(NormalModel),
            typeof(NullableModel),
            typeof(GenericModel),
            typeof(TypeEnum),
        };
        var code = _generator.GetCode();
        var expected = """
/* Generated by TypeSharpV3 dev-version */
export interface Generic<T> {
  value: T;
}
export interface GenericModel {
  genericString: Generic<string>;
  genericGuid: Generic<string>;
}
export enum HttpStatus {
  None = 0,
  OK = 200,
  NotFound = 404
}
export interface NormalModel {
  guid: string;
  int: number;
  str?: string;
  obj?: any;
  status: HttpStatus;
  dateOnly: string;
  requiedGuid: string;
  requiedInt: number;
  requiedStr: string;
  requiedObj: any;
  requiedStatus: HttpStatus;
  requiedDateOnly: string;
  onlyGet?: number;
  privateSet?: number;
}
export interface NullableModel {
  guid?: string;
  int?: number;
  str?: string;
  obj?: any;
  status?: HttpStatus;
  dateOnly?: string;
  requiedGuid: string;
  requiedInt: number;
  requiedStr: string;
  requiedObj: any;
  requiedStatus: HttpStatus;
  requiedDateOnly: string;
  onlyGet?: number;
  privateSet?: number;
}
export interface TypeEnum {
}
""";
        Assert.Equal(expected, code);
    }
}
